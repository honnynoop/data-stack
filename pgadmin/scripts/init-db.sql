CREATE DATABASE superset;

\connect airflow;

CREATE SCHEMA IF NOT EXISTS raw;
CREATE SCHEMA IF NOT EXISTS staging;
CREATE SCHEMA IF NOT EXISTS marts;

-- ============================================================
-- RAW 테이블 정의
-- ============================================================

CREATE TABLE IF NOT EXISTS raw.customers (
    customer_id   SERIAL PRIMARY KEY,
    name          VARCHAR(100)  NOT NULL,
    email         VARCHAR(150)  UNIQUE NOT NULL,
    phone         VARCHAR(20),
    city          VARCHAR(100),
    region        VARCHAR(50),
    age_group     VARCHAR(20),
    gender        VARCHAR(10),
    channel       VARCHAR(30),
    signup_date   DATE,
    created_at    TIMESTAMP DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS raw.products (
    product_id   SERIAL PRIMARY KEY,
    name         VARCHAR(200) NOT NULL,
    category     VARCHAR(100),
    subcategory  VARCHAR(100),
    brand        VARCHAR(100),
    price        NUMERIC(10,2),
    cost         NUMERIC(10,2),
    stock_qty    INTEGER DEFAULT 100,
    created_at   TIMESTAMP DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS raw.orders (
    order_id      SERIAL PRIMARY KEY,
    customer_id   INTEGER REFERENCES raw.customers(customer_id),
    product_id    INTEGER REFERENCES raw.products(product_id),
    quantity      INTEGER       NOT NULL,
    unit_price    NUMERIC(10,2) NOT NULL,
    discount_rate NUMERIC(5,4)  DEFAULT 0,
    order_date    DATE          NOT NULL,
    status        VARCHAR(20)   NOT NULL DEFAULT 'completed',
    channel       VARCHAR(30),
    created_at    TIMESTAMP DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS raw.marketing_spend (
    id            SERIAL PRIMARY KEY,
    spend_date    DATE          NOT NULL,
    channel       VARCHAR(50)   NOT NULL,
    campaign      VARCHAR(100),
    spend_amount  NUMERIC(12,2) NOT NULL,
    impressions   INTEGER,
    clicks        INTEGER,
    created_at    TIMESTAMP DEFAULT NOW()
);

